export const locales = ["id", "en"] as const;

export type Locale = (typeof locales)[number];

/** Indonesian is the primary audience, so it is also the default locale. */
export const defaultLocale: Locale = "id";

/** A value that exists in every supported language. */
export type Localized<T = string> = Record<Locale, T>;

/** Terse constructor so the data files stay readable. */
export function l<T>(id: T, en: T): Localized<T> {
  return { id, en };
}

export type LocaleMeta = {
  /** Short label used by the language switcher. */
  label: string;
  /** Endonym, used in accessible names. */
  name: string;
  htmlLang: string;
  ogLocale: string;
  path: string;
};

export const localeMeta: Record<Locale, LocaleMeta> = {
  id: {
    label: "ID",
    name: "Bahasa Indonesia",
    htmlLang: "id",
    ogLocale: "id_ID",
    path: "/id",
  },
  en: {
    label: "EN",
    name: "English",
    htmlLang: "en",
    ogLocale: "en_US",
    path: "/en",
  },
};

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value);
}

export function otherLocale(locale: Locale): Locale {
  return locale === "id" ? "en" : "id";
}

/** One placeholder CV per language, generated by `npm run resume`. */
export const resumeUrls: Record<Locale, string> = {
  id: "/resume-id.pdf",
  en: "/resume-en.pdf",
};
